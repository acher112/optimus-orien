def infer_country_name(city_name: str = '', listing_country=None, client_country: str = '') -> str:
    if client_country and str(client_country).strip():
        return str(client_country).strip()[:100]
    if listing_country:
        if isinstance(listing_country, str) and listing_country.strip():
            return listing_country.strip()
        if isinstance(listing_country, list) and listing_country:
            return str(listing_country[0]).strip()
    c = (city_name or '').strip().lower()
    for token, country in CITY_COUNTRY_MAP.items():
        if token in c:
            return country
    return 'Pakistan'


def resolve_participant_location(user=None, school=None, client_country: str = '', client_region: str = '') -> tuple[str, str]:
    """Resolves (country, region) for a quiz participant."""
    from core.models import PublicCampusListing

    target_school = school or (getattr(user, 'school', None) if user else None)
    city = (getattr(target_school, 'city', '') or '').strip() if target_school else ''
    listing = PublicCampusListing.objects.filter(school=target_school).first() if target_school else None
    listing_country = listing.country if listing else None

    country = infer_country_name(city, listing_country, client_country=client_country)
    if client_region and client_region.strip():
        region = client_region.strip()[:120]
    elif city and city.lower() != country.lower():
        region = f"{city}, {country}"
    else:
        region = country
    return country, region


def normalize_quiz_scope(scope_raw: str) -> str:
    val = (scope_raw or 'worldwide').strip().lower()
    if val in ('our_campus', 'campus', 'school', 'my_campus'):
        return 'our_campus'
    if val in ('org_campuses', 'all_our_campuses', 'organisation', 'organization', 'all_campuses'):
        return 'org_campuses'
    return 'worldwide'


def format_scope_label(scope_raw: str) -> str:
    norm = normalize_quiz_scope(scope_raw)
    if norm == 'our_campus':
        return 'Only Our Campus'
    if norm == 'org_campuses':
        return 'All Our Campuses'
    return 'Worldwide (All Campuses)'


def get_student_quiz_performance(student=None, user=None) -> dict:
    """
    Returns unified quiz attempt history and aggregate metrics for a student's profile
    & academic performance record.
    """
    from core.models import QuizAttempt

    q_filter = Q()
    if student is not None:
        q_filter |= Q(student=student)
        if getattr(student, 'user_id', None):
            q_filter |= Q(user_id=student.user_id)
    if user is not None:
        q_filter |= Q(user=user)

    if not q_filter:
        return {
            'attempts': [],
            'summary': {
                'total_attempted': 0,
                'average_score': None,
                'average_accuracy': None,
                'best_score': None,
                'total_time_seconds': 0,
            },
        }

    attempts_qs = (
        QuizAttempt.objects.filter(q_filter)
        .select_related('competition', 'competition__created_by', 'competition__sponsor_school')
        .order_by('-submitted_at')
    )

    seen_ids = set()
    attempts = []
    scores = []
    accuracies = []
    total_time = 0

    for att in attempts_qs:
        if att.id in seen_ids:
            continue
        seen_ids.add(att.id)
        comp = att.competition
        score_val = float(att.score_percentage)
        acc_val = float(att.accuracy_percentage)
        scores.append(score_val)
        accuracies.append(acc_val)
        total_time += int(att.time_spent_seconds or 0)

        mins = att.time_spent_seconds // 60
        secs = att.time_spent_seconds % 60
        creator = comp.created_by
        creator_name = (
            (creator.get_full_name() or creator.username)
            if creator
            else (comp.sponsor_name or 'Optimus Orien')
        )

        attempts.append({
            'id': att.id,
            'competition_id': comp.id,
            'title': comp.title,
            'subject': comp.subject,
            'topic': getattr(comp, 'topic', '') or '',
            'difficulty': comp.difficulty,
            'scope': normalize_quiz_scope(comp.scope),
            'scope_label': format_scope_label(comp.scope),
            'score_percentage': score_val,
            'raw_score': float(att.raw_score),
            'total_marks': float(att.total_marks),
            'accuracy_percentage': acc_val,
            'time_spent_seconds': att.time_spent_seconds,
            'time_display': f"{mins:02d}m {secs:02d}s",
            'country': att.country or 'Pakistan',
            'region': att.region or att.country or 'Pakistan',
            'created_by_name': creator_name,
            'is_official': bool(att.is_official),
            'submitted_at': att.submitted_at.isoformat(),
            'submitted_date': att.submitted_at.strftime('%Y-%m-%d'),
            'graded_breakdown': att.graded_breakdown or [],
        })

    total_att = len(attempts)
    return {
        'attempts': attempts,
        'summary': {
            'total_attempted': total_att,
            'average_score': round(sum(scores) / total_att, 1) if total_att else None,
            'average_accuracy': round(sum(accuracies) / total_att, 1) if total_att else None,
            'best_score': round(max(scores), 1) if total_att else None,
            'total_time_seconds': total_time,
        },
    }
