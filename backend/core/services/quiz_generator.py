def _resolve_bank_key(subject: str, topic: str = '') -> str | None:
    s_lower = (subject or '').strip().lower()
    if s_lower in DUMMY_QUESTION_BANK:
        return s_lower
    if s_lower in SUBJECT_ALIASES:
        return SUBJECT_ALIASES[s_lower]
    combined = f"{s_lower} {(topic or '').strip().lower()}"
    for alias, key in SUBJECT_ALIASES.items():
        if re.search(rf'\b{re.escape(alias)}\b', combined):
            return key
    return None


def _generate_with_llm(subject: str, topic: str, difficulty: str, grade_level: str, num_questions: int) -> list:
    """
    Future LLM integration hook (Groq / OpenAI GPT).
    When GROQ_API_KEY or OPENAI_API_KEY is configured and enabled in the future,
    this function will query the selected LLM and return structured JSON questions
    matching the exact schema below.
    """
    raise NotImplementedError('External LLM provider not configured; using dummy_ai generator.')


def generate_quiz_questions(
    subject: str,
    topic: str = '',
    difficulty: str = 'Intermediate',
    grade_level: str = 'Grade 8',
    num_questions: int = 5,
    provider: str = 'dummy_ai',
) -> dict:
    """
    Generates a randomized list of quiz questions for any subject (preset or custom)
    and difficulty level.
    """
    count = max(1, min(int(num_questions or 5), 25))
    diff = difficulty or 'Intermediate'
    # Normalize display labels like "Easy (Foundation)" -> "Foundation"
    for canonical in ('Foundation', 'Intermediate', 'Advanced', 'Olympiad'):
        if canonical.lower() in diff.lower():
            diff = canonical
            break

    # Placeholder hook for future Groq / GPT LLM support
    if provider in ('groq', 'openai') and (os.getenv('GROQ_API_KEY') or os.getenv('OPENAI_API_KEY')):
        try:
            llm_qs = _generate_with_llm(subject, topic, diff, grade_level, count)
            return {'source': provider, 'questions': llm_qs}
        except NotImplementedError:
            pass

    bank_key = _resolve_bank_key(subject, topic)
    selected_questions = []

    if bank_key and bank_key in DUMMY_QUESTION_BANK:
        pool = list(DUMMY_QUESTION_BANK[bank_key])
        matching_diff = [q for q in pool if q.get('difficulty', '').lower() == diff.lower()]
        other_diff = [q for q in pool if q.get('difficulty', '').lower() != diff.lower()]
        random.shuffle(matching_diff)
        random.shuffle(other_diff)
        candidates = matching_diff + other_diff

        for q in candidates[:count]:
            selected_questions.append(_shuffle_mcq_options(q))

        # If more questions requested than available in that bank subject, supplement cleanly
        if len(selected_questions) < count:
            needed = count - len(selected_questions)
            extra = _build_custom_subject_questions(subject, topic, diff, grade_level, needed)
            selected_questions.extend(extra)
    else:
        # Custom subject: generate randomized topic-aware questions tailored to this custom subject
        selected_questions.extend(
            _build_custom_subject_questions(subject, topic, diff, grade_level, count)
        )

    # Shuffle final question list and assign 1-based order
    random.shuffle(selected_questions)
    for idx, q in enumerate(selected_questions, start=1):
        q['order'] = idx
        q.setdefault('unit', '')
        q.setdefault('tolerance', 0.0)
        q.setdefault('marks', 15 if diff == 'Olympiad' else 10)

    return {
        'source': 'dummy_ai',
        'difficulty': diff,
        'subject': subject,
        'topic': topic,
        'questions': selected_questions,
    }


def ensure_competition_has_questions(comp) -> None:
    """Auto-populates dummy AI questions if an existing QuizCompetition has 0 questions."""
    from core.models import QuizQuestion
    if comp.questions.exists():
        return
    generated = generate_quiz_questions(
        subject=comp.subject,
        topic=getattr(comp, 'topic', '') or comp.title,
        difficulty=comp.difficulty or 'Intermediate',
        grade_level=comp.grade_level or 'Grade 8',
        num_questions=4,
    )
    total_marks = 0
    for q in generated['questions']:
        marks = int(q.get('marks', 10))
        total_marks += marks
        QuizQuestion.objects.create(
            competition=comp,
            order=q['order'],
            prompt=q['prompt'],
            question_type=q['question_type'],
            options=q.get('options', []),
            correct_answer=q.get('correct_answer', {}),
            tolerance=q.get('tolerance', 0.0),
            unit=q.get('unit', ''),
            explanation=q.get('explanation', ''),
            marks=marks,
        )
    if total_marks > 0:
        comp.total_marks = total_marks
        comp.save(update_fields=['total_marks'])


