def _shuffle_mcq_options(q: dict) -> dict:
    """Shuffles MCQ options and remaps A/B/C/D while keeping correct_answer accurate."""
    item = copy.deepcopy(q)
    if item.get('question_type') == 'multiple_choice' and item.get('options'):
        old_correct_id = str(item.get('correct_answer', {}).get('id', '')).upper()
        correct_text = None
        texts = []
        for opt in item['options']:
            texts.append(opt.get('text', ''))
            if str(opt.get('id', '')).upper() == old_correct_id:
                correct_text = opt.get('text', '')
        random.shuffle(texts)
        letters = ['A', 'B', 'C', 'D', 'E']
        new_opts = []
        new_correct_id = 'A'
        for idx, txt in enumerate(texts):
            lid = letters[idx] if idx < len(letters) else str(idx + 1)
            new_opts.append({'id': lid, 'text': txt})
            if txt == correct_text:
                new_correct_id = lid
        item['options'] = new_opts
        item['correct_answer'] = {'id': new_correct_id}
    return item


